//! Writes runtime/ca_roots.h from a PEM bundle of root certificates (Mozilla's, as curl publishes it at
//! https://curl.se/ca/cacert.pem): the Windows ROOT store the runtime shows games, so their own TLS (OpenSSL in Unreal's
//! libcurl, the EOS SDK) can check real servers.
//!   cargo run --release --manifest-path rustlift/Cargo.toml --bin gen_ca_roots -- cacert.pem runtime/ca_roots.h
use std::fmt::Write as _;

fn b64(s: &str) -> Vec<u8> {
    let val = |c: u8| match c {
        b'A'..=b'Z' => Some(c - b'A'),
        b'a'..=b'z' => Some(c - b'a' + 26),
        b'0'..=b'9' => Some(c - b'0' + 52),
        b'+' => Some(62),
        b'/' => Some(63),
        _ => None,
    };
    let (mut out, mut acc, mut bits) = (Vec::new(), 0u32, 0);
    for v in s.bytes().filter_map(val) {
        acc = acc << 6 | v as u32;
        bits += 6;
        if bits >= 8 {
            bits -= 8;
            out.push((acc >> bits) as u8);
        }
    }
    out
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let (Some(src), Some(dst)) = (args.first(), args.get(1)) else {
        eprintln!("usage: gen_ca_roots <cacert.pem> <ca_roots.h>");
        std::process::exit(2)
    };
    let pem = std::fs::read_to_string(src).expect("bundle");
    let stamp = pem.lines().find(|l| l.contains("as of:")).map(|l| l.trim_start_matches('#').trim().to_string()).unwrap_or_default();
    let mut certs = Vec::new();
    let mut rest = pem.as_str();
    while let Some(a) = rest.find("-----BEGIN CERTIFICATE-----") {
        let body = &rest[a + 27..];
        let Some(e) = body.find("-----END CERTIFICATE-----") else { break };
        certs.push(b64(&body[..e]));
        rest = &body[e..];
    }
    let mut out = format!(
        "/* Root certificates for the runtime's Windows ROOT store, generated by rustlift/src/bin/gen_ca_roots.rs from\n   Mozilla's bundle (https://curl.se/ca/cacert.pem; {stamp}). */\n#pragma once\n\n"
    );
    for (i, c) in certs.iter().enumerate() {
        let _ = write!(out, "static const unsigned char ca_root_{i}[{}] = {{", c.len());
        for (k, b) in c.iter().enumerate() {
            if k % 24 == 0 {
                out.push_str("\n   ");
            }
            let _ = write!(out, " {b},");
        }
        out.push_str("\n};\n");
    }
    let _ = write!(out, "\nstatic const struct {{ const unsigned char* der; unsigned size; }} ca_roots[{}] = {{\n", certs.len());
    for (i, c) in certs.iter().enumerate() {
        let _ = writeln!(out, "    {{ ca_root_{i}, {} }},", c.len());
    }
    let _ = write!(out, "}};\n#define CA_ROOT_COUNT {}\n", certs.len());
    std::fs::write(dst, out).expect("write");
    println!("{} root certificates", certs.len());
}
