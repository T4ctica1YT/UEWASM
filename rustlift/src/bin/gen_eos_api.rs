//! Writes runtime/eos_api.h: every function of the EOS SDK (Epic Online Services) C API as the runtime needs it to
//! stand in for EOSSDK-Win64/Win32-Shipping.dll: its name, what it returns, its argument count, the bytes a 32-bit
//! (stdcall) call pops, and for asynchronous calls where the completion callback and its ClientData are.
//!
//!     cargo run --release --manifest-path rustlift/Cargo.toml --bin gen_eos_api -- <EOS SDK>/SDK/Include [out.h]
//!
//! Only these facts go in the table, not Epic's headers. The C API keeps old struct layouts working (each options
//! struct carries its ApiVersion, new fields come last), so the newest SDK's list covers games built on older ones.
use regex::Regex;
use std::path::{Path, PathBuf};

/// return kinds, as the runtime's eos_api.h names them
const R_VOID: u8 = 0;
const R_RESULT: u8 = 1;
const R_NOTIFY: u8 = 2;
const R_INT: u8 = 3;
const R_BOOL: u8 = 4;
const R_PTR: u8 = 5;

fn ret_kind(r: &str) -> u8 {
    let r = r.trim();
    if r == "void" {
        R_VOID
    } else if r == "EOS_EResult" {
        R_RESULT
    } else if r == "EOS_NotificationId" {
        R_NOTIFY
    } else if r == "EOS_Bool" {
        R_BOOL
    } else if r.contains('*') || r.starts_with("EOS_H") || r == "EOS_ProductUserId" || r == "EOS_EpicAccountId" {
        R_PTR
    } else {
        R_INT
    }
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    if args.len() < 2 {
        eprintln!("usage: gen_eos_api <EOS SDK>/SDK/Include [out.h]");
        std::process::exit(2);
    }
    let src = PathBuf::from(&args[1]);
    let out = args.get(2).map(PathBuf::from)
        .unwrap_or_else(|| Path::new(env!("CARGO_MANIFEST_DIR")).join("..").join("runtime").join("eos_api.h"));
    let decl = Regex::new(r"EOS_DECLARE_FUNC\(([^)]*)\)\s*(EOS_\w+)\s*\(([^;]*)\)\s*;").unwrap();
    let mut files: Vec<PathBuf> = std::fs::read_dir(&src).expect("include dir").filter_map(|e| e.ok()).map(|e| e.path())
        .filter(|p| p.extension().map_or(false, |e| e == "h")).collect();
    files.sort();
    let mut fns: Vec<(String, u8, u8, u8, u8, u8)> = Vec::new();
    for f in files {
        let text = String::from_utf8_lossy(&std::fs::read(&f).expect("read header")).to_string();
        for c in decl.captures_iter(&text) {
            let name = c[2].to_string();
            if fns.iter().any(|x| x.0 == name) {
                continue;
            }
            let params: Vec<String> = c[3].split(',').map(|p| p.trim().to_string()).filter(|p| !p.is_empty() && p != "void").collect();
            let (mut pops, mut cb, mut cd) = (0u8, 255u8, 255u8);
            for (i, p) in params.iter().enumerate() {
                let wide = p.contains("EOS_NotificationId") || p.contains("uint64_t") || p.contains("int64_t") || p.contains("double");
                pops += if wide && !p.contains('*') { 8 } else { 4 };
                let pname = p.rsplit(|ch: char| ch == ' ' || ch == '*').next().unwrap_or("");
                if pname == "CompletionDelegate" {
                    cb = i as u8;
                }
                if pname == "ClientData" {
                    cd = i as u8;
                }
            }
            // a notification's function (AddNotify*): the callback-typed argument, kept where a completion would be
            if cb == 255 {
                for (i, p) in params.iter().enumerate() {
                    let ty = p.trim_start_matches("const ").split_whitespace().next().unwrap_or("");
                    if ty.ends_with("Callback") || ty.ends_with("CallbackV2") {
                        cb = i as u8;
                    }
                }
            }
            fns.push((name, ret_kind(&c[1]), params.len() as u8, pops, cb, cd));
        }
    }
    fns.sort();
    let mut lines = vec![
        "/* generated by gen_eos_api (rustlift/src/bin) from the EOS SDK headers: each EOS C API function's name, return".to_string(),
        "   kind (EOS_R_*), argument count, the bytes a 32-bit (stdcall) call pops, and the argument index of the completion".to_string(),
        "   (or notification) callback and of its ClientData (255 when there is none) */".to_string(),
        "enum { EOS_R_VOID, EOS_R_RESULT, EOS_R_NOTIFY, EOS_R_INT, EOS_R_BOOL, EOS_R_PTR };".to_string(),
        "typedef struct { const char* name; unsigned char ret, nargs, pops, cb, cd; } EosFn;".to_string(),
        String::new(),
        "static const EosFn eos_fns[] = {".to_string(),
    ];
    for (n, r, a, p, cb, cd) in &fns {
        lines.push(format!("    {{ \"{}\", {}, {}, {}, {}, {} }},", n, r, a, p, cb, cd));
    }
    lines.push("};".to_string());
    lines.push(format!("#define EOS_FN_COUNT {}", fns.len()));
    // one entry point per function, so a call knows which one it is: X(i) is defined by the includer
    let xs: Vec<String> = (0..fns.len()).map(|i| format!("X({})", i)).collect();
    for (k, chunk) in xs.chunks(16).enumerate() {
        let tail = if (k + 1) * 16 < xs.len() { " \\" } else { "" };
        lines.push(format!("{}{}{}", if k == 0 { "#define EOS_ENTRIES " } else { "    " }, chunk.join(" "), tail));
    }
    lines.push(String::new());
    std::fs::write(&out, lines.join("\n")).expect("write header");
    println!("{}: {} functions", out.display(), fns.len());
}
